    Color32 PixelIcones::Couleur(char c)
    {
        switch (c)
        {
            case 'k': return Pal::C("1d1612");
            case 'w': return Pal::C("f6f0e2");
            case 'r': return Pal::C("d4483b");
            case 'R': return Pal::C("8e2a22");
            case 'y': return Pal::C("f0c04c");
            case 'Y': return Pal::C("b5832a");
            case 'g': return Pal::C("c9ccd0");
            case 'G': return Pal::C("838a92");
            case 'b': return Pal::C("5aa0e6");
            case 'B': return Pal::C("2f5e9e");
            case 'v': return Pal::C("6fbf4a");
            case 'V': return Pal::C("3f7a2c");
            case 'p': return Pal::C("a46ad8");
            case 'P': return Pal::C("5e3590");
            case 'o': return Pal::C("ec8a32");
            case 'n': return Pal::C("9a6a3c");
            case 'N': return Pal::C("5e3e22");
            case 's': return Pal::C("e8b48e");
            default: return Color32(0, 0, 0, 0);
        }
    }

    Dico<string, Liste<Color32>>& PixelIcones::Dynamiques()
    {
        static Dico<string, Liste<Color32>> d;
        return d;
    }

    Color32 PixelIcones::Pixel(const string& id, int x, int y)
    {
        if (auto* px = Dynamiques().Chercher(id))
            return x >= 0 && x < Taille && y >= 0 && y < Taille && px->Count() == Taille * Taille ? (*px)[y * Taille + x] : Color32(0, 0, 0, 0);
        auto* d = Dessins().Chercher(id);
        if (d == nullptr) return Color32(0, 0, 0, 0);
        int ligne = d->Count() - 1 - y;
        if (ligne < 0 || ligne >= d->Count() || x < 0 || x >= static_cast<int>((*d)[ligne].size())) return Color32(0, 0, 0, 0);
        return Couleur((*d)[ligne][static_cast<size_t>(x)]);
    }
